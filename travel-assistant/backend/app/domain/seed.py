def seed_candidates(city: str = "成都") -> List[Candidate]:
    if city != "成都":
        return []
    items = []
    for idx, raw in enumerate(CHENGDU_POIS):
        prefix = {"attraction": "a", "meal": "f", "hotel": "h"}[raw["kind"]]
        items.append(
            Candidate(
                candidate_id=f"{prefix}{idx + 1}",
                source="seed",
                confidence="estimate",
                booking_url=f"https://www.amap.com/search?query={raw['name']}",
                **raw,
            )
        )
    return items


